// Machine/CgaFont.cpp
//
// Every glyph below was drawn by hand for this project (ruling D14). None of these bytes was copied
// from IBM, from a BIOS or ROM dump, from an emulator, from a font file or from the web.
//
// The style follows the CGA's normal font: vertical strokes two dots wide, horizontal strokes one
// dot tall; capitals and digits on rows 0-6 with row 7 left for descenders; lower case on rows 2-6;
// and column 7 dark, so that neighbouring characters stand apart. Box-drawing pieces run to the
// edges of the cell so that they join: a single vertical line on columns 3-4, a double one on
// columns 1-2 and 5-6, a single horizontal line on row 3, and a double one on rows 2 and 4.
